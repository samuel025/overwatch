"""Write overwatch.traces.yaml: the demo config plus the trace store (Tempo), so the Investigator can read real requests.

    DEMO_OTLP_ENDPOINT=http://tempo:4318 docker compose --profile tracing up -d --build     # the shop emits traces, Tempo stores them
    python scripts/make_traces_config.py [http://127.0.0.1:3200]                           # asks Tempo what it has and writes the config
    overwatch -c overwatch.traces.yaml run

It adds the `traces` source, its commands to the catalog, and two evidence queries (slowest and failing traces). The demo's own
checks stay as they are, so the faults are detected exactly as before; traces change how well they are explained.
"""
import sys
from pathlib import Path

import yaml

from overwatch.discovery import _lit
from overwatch.discovery.traces import discover_traces

root = Path(__file__).resolve().parent.parent
url = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:3200"
cfg = yaml.safe_load((root / "overwatch.yaml").read_text())
tr = discover_traces(url)

cfg["sources"]["traces"] = tr["source"]
cfg["catalog"] = _lit(cfg["catalog"].rstrip() + "\n\n" + tr["catalog"])
cfg["evidence"] = list(cfg.get("evidence", [])) + tr["evidence"]
out = root / "overwatch.traces.yaml"
out.write_text("# GENERATED by scripts/make_traces_config.py from overwatch.yaml. Do not edit by hand.\n"
               + yaml.safe_dump(cfg, sort_keys=False, width=120))
print(f"Wrote {out}: {tr['kind']} at {url}, services {', '.join(tr['services'])}")
