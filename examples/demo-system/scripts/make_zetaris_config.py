"""Write overwatch.zetaris.yaml: the demo config with every business-data query going through Zetaris.

Reads overwatch.yaml (Postgres SQL, two direct sources) and rewrites it for Zetaris (Spark SQL):
  - one `zetaris` source replaces opsdb + shopdb; tables are qualified (opsdb.deploys, shopdb.orders)
  - time windows use current_timestamp() - INTERVAL n UNIT, and Postgres casts are dropped
  - live Postgres internals (pg_stat_activity, pg_locks, pg_indexes ...) are not tables, so they stay on a
    direct `shopdb_live` source next to Zetaris

Register the databases first:  python scripts/register_zetaris.py
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
text = (root / "overwatch.yaml").read_text()

head, rest = text.split("\nsources:\n", 1)
_, rest = rest.split("\ncatalog: |\n", 1)
catalog, tail = rest.split("\ntopology:", 1)

head = head.replace(
    "# Until Zetaris is set up, the two databases are separate direct sources. With Zetaris,\n"
    "# replace both with a single `zetaris` source that federates shopdb + opsdb, and update the\n"
    "# catalog to the Zetaris table names, so one query can join metrics, deploys and DB stats.",
    "# GENERATED by scripts/make_zetaris_config.py from overwatch.yaml. Do not edit by hand.\n"
    "# Zetaris is the data layer: shopdb + opsdb are registered in it and one query can join metrics,\n"
    "# deploys and business tables. Run `python scripts/register_zetaris.py` once first.")

registration = '''
# Overwatch's own history lives in its Postgres (deploy/docker-compose.yml); Zetaris reads it from there. The demo
# databases are registered in Zetaris at every start, so a restarted Zetaris heals itself.
state_url: ${OVERWATCH_STATE_URL}
register:
  opsdb: postgresql+psycopg://overwatch_ro:overwatch_ro@localhost:15432/opsdb
  shopdb: postgresql+psycopg://overwatch_ro:overwatch_ro@localhost:15432/shopdb
'''

sources = '''
sources:
  zetaris:
    type: zetaris
    jdbc_url: ${ZETARIS_JDBC_URL}
    driver_class: ${ZETARIS_DRIVER_CLASS}
    driver_jar: ${ZETARIS_DRIVER_JAR}
    username: ${ZETARIS_USER}
    password: ${ZETARIS_PASSWORD}
  shopdb_live:        # live Postgres internals (sessions, locks, indexes) are not tables Zetaris can register
    type: postgres
    url: postgresql+psycopg://overwatch_ro:overwatch_ro@localhost:15432/shopdb
'''

catalog_zetaris = '''
catalog: |
  All business and monitoring data is in Zetaris (Spark SQL). Tables are written <database>.<table>, and one
  query may join tables from both databases.
  opsdb (operations data):
    opsdb.request_metrics(ts, service, instance, endpoint, requests, rps, p50_ms, p95_ms, error_rate)
      one row per instance+endpoint every 10 seconds. services: gateway, orders, payments
      (payments has instances payments-a and payments-b).
    opsdb.app_logs(ts, service, instance, level, message)   level INFO, WARN or ERROR
    opsdb.container_metrics(ts, service, instance, cpu_pct, cpu_limit_cores, mem_mb, mem_limit_mb, restarts,
                            oom_killed, status)
      every 10 seconds per container (gateway, orders, payments-a, payments-b, postgres). cpu_pct is percent
      of one core; restarts is cumulative; oom_killed means the last exit was an out-of-memory kill.
    opsdb.deploys(ts, service, version, author, description)
      every code release and config change, for all teams (many are unrelated to any given incident)
    opsdb.tickets(key, created, title, status, resolution)   past incident tickets
  shopdb (application database):
    shopdb.orders(id, customer_id, amount, status, created_at), shopdb.customers(id, name, created_at),
    shopdb.payments(id, order_id, amount, status, created_at)
    A query can join across the two databases, e.g. opsdb.deploys with shopdb.payments to see what a release did to payments.
    shopdb.pg_stat_statements(query, calls, mean_exec_time, total_exec_time, rows)
  Live Postgres internals are NOT in Zetaris. Query them with source shopdb_live (Postgres SQL):
      pg_indexes(schemaname, tablename, indexname, indexdef)
      pg_stat_user_tables(relname, seq_scan, seq_tup_read, idx_scan, n_live_tup)
      pg_stat_activity(pid, application_name, state, wait_event_type, wait_event, query, query_start,
                       xact_start, state_change)   -- who is connected and what they are doing/waiting on
      pg_locks(locktype, relation::regclass, mode, granted, pid); pg_blocking_pids(pid) returns blockers
    Service instances connect with application_name shop-<instance>, e.g. shop-orders, shop-payments-a.
  Time windows in Zetaris: ts > current_timestamp() - INTERVAL 5 MINUTES (units: SECONDS, MINUTES, HOURS, DAYS).
  Data is current; compare the last few minutes with the last hour.
'''

# queries: only the parts after `checks:`/`impact:`/`evidence:` use SQL; rewrite them all the same way
tail = "\ntopology:" + tail


def interval(m: re.Match) -> str:
    return f"current_timestamp() - INTERVAL {m.group(1)} {m.group(2).upper()}"


tail = re.sub(r"now\(\) - interval '(\d+) (second|minute|hour|day)s?'", interval, tail)
tail = re.sub(r"now\(\) - interval '(\d+) (second|minute|hour|day)s?'", interval, tail)
tail = tail.replace("::numeric", "")
# Spark SQL has no DISTINCT ON: take the newest row per instance with a window function
distinct_on = (
    "SELECT DISTINCT ON (instance) instance, status, restarts, oom_killed,\n"
    "        round(cpu_pct, 1) AS cpu_pct, round(mem_mb) AS mem_mb, mem_limit_mb\n"
    "      FROM container_metrics WHERE ts > now() - interval '1 minute' ORDER BY instance, ts DESC")
assert distinct_on.replace("now() - interval '1 minute'", "current_timestamp() - INTERVAL 1 MINUTE") in tail
tail = tail.replace(
    distinct_on.replace("now() - interval '1 minute'", "current_timestamp() - INTERVAL 1 MINUTE"),
    "SELECT instance, status, restarts, oom_killed, round(cpu_pct, 1) AS cpu_pct, round(mem_mb) AS mem_mb, mem_limit_mb\n"
    "      FROM (SELECT *, row_number() OVER (PARTITION BY instance ORDER BY ts DESC) AS rn FROM opsdb.container_metrics\n"
    "            WHERE ts > current_timestamp() - INTERVAL 1 MINUTE) WHERE rn = 1 ORDER BY instance")
tail = re.sub(r"\b(FROM|JOIN)\s+(request_metrics|app_logs|container_metrics|deploys|tickets)\b", r"\1 opsdb.\2", tail)
# live-database sessions stay on Postgres
tail = re.sub(r"(name: db_activity\n(?:.*\n)*?\s+source: )shopdb\b", r"\1shopdb_live", tail)
tail = re.sub(r"(\n\s+source: )(opsdb|shopdb)\b", r"\1zetaris", tail)
tail = tail.replace("zetaris\n    query: >\n      SELECT application_name", "shopdb_live\n    query: >\n      SELECT application_name")

# The Zetaris-only evidence: one query across both databases (deploys live in opsdb, payments in shopdb).
cross = """  - name: deploys_vs_payments
    label: Payments per minute before and after each recent change (joins opsdb.deploys with shopdb.payments)
    source: zetaris
    query: >
      SELECT d.ts AS deployed_at, d.service, d.version,
        round(sum(CASE WHEN p.created_at >= d.ts - INTERVAL 5 MINUTES AND p.created_at < d.ts THEN 1 ELSE 0 END) / 5.0, 1) AS payments_per_min_before,
        round(sum(CASE WHEN p.created_at >= d.ts AND p.created_at < d.ts + INTERVAL 5 MINUTES THEN 1 ELSE 0 END) / 5.0, 1) AS payments_per_min_after
      FROM opsdb.deploys d CROSS JOIN shopdb.payments p
      WHERE d.ts > current_timestamp() - INTERVAL 30 MINUTES AND p.created_at > current_timestamp() - INTERVAL 40 MINUTES
      GROUP BY d.ts, d.service, d.version ORDER BY d.ts DESC LIMIT 8
"""
assert "  - name: top_errors" in tail
tail = tail.replace("  - name: top_errors", cross + "  - name: top_errors", 1)

out = head + registration + sources + catalog_zetaris + tail
(root / "overwatch.zetaris.yaml").write_text(out)
print("wrote", root / "overwatch.zetaris.yaml")
